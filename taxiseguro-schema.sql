-- 1. Table: categorias_vehiculos
CREATE TABLE IF NOT EXISTS public.categorias_vehiculos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone DEFAULT now(),
    nombre text NOT NULL,
    base_minima numeric NOT NULL DEFAULT 0,
    base_precio_km numeric NOT NULL DEFAULT 0,
    base_espera_minuto numeric NOT NULL DEFAULT 0,
    base_espera_hora numeric NOT NULL DEFAULT 0,
    final_minima numeric NOT NULL DEFAULT 0,
    final_precio_km numeric NOT NULL DEFAULT 0,
    final_espera_minuto numeric NOT NULL DEFAULT 0,
    final_espera_hora numeric NOT NULL DEFAULT 0
);

-- 2. Table: conductores
CREATE TABLE IF NOT EXISTS public.conductores (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    nombre text NOT NULL,
    direccion text,
    telefono text,
    correo text UNIQUE NOT NULL,
    contrasena text,
    created_at timestamp with time zone DEFAULT now(),
    licencia_url text,
    ine_url text,
    comprobante_url text,
    seguro_url text,
    tarjeta_url text,
    curp_url text,
    acta_url text,
    alta_firmada_url text,
    registro_status text DEFAULT 'pending',
    marca text,
    modelo text,
    ano text,
    color text,
    placas text,
    puertas text
);

-- 3. Table: Vehículos (with accent)
CREATE TABLE IF NOT EXISTS public."Vehículos" (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone DEFAULT now(),
    "Modelo" text NOT NULL,
    imagen text,
    "capacidadDeCarga" integer DEFAULT 4,
    "Disponibilidad" boolean DEFAULT true,
    categoria_id bigint REFERENCES public.categorias_vehiculos(id) ON DELETE SET NULL,
    marca text,
    "año" integer,
    color text,
    placas text,
    puertas integer,
    conductor_id uuid REFERENCES public.conductores(id) ON DELETE SET NULL,
    "VerEnWeb" boolean DEFAULT true
);

-- 4. Table: users
CREATE TABLE IF NOT EXISTS public.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone DEFAULT now(),
    nombre text NOT NULL,
    correo text UNIQUE NOT NULL,
    telefono text,
    "isAdmin" boolean DEFAULT false,
    "perfilCompletado" boolean DEFAULT false,
    "IDUser" uuid,
    fotodeperfil text,
    "isConductor" boolean DEFAULT false,
    isadmin boolean DEFAULT false
);

-- 5. Table: cotizaciones
CREATE TABLE IF NOT EXISTS public.cotizaciones (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    created_at timestamp with time zone DEFAULT now(),
    vehicle_model text,
    schedule text,
    booker_name text,
    passenger_phone text,
    booker_phone text,
    zone_rate text,
    payment_method text,
    pickup_address text,
    pickup_zip text,
    pickup_ext_num text,
    pickup_municipality text,
    dropoff_address text,
    dropoff_zip text,
    dropoff_municipality text,
    adults integer DEFAULT 1,
    kids integer DEFAULT 0,
    luggage_10kg integer DEFAULT 0,
    luggage_25kg integer DEFAULT 0,
    carry_on integer DEFAULT 0,
    extra_destination boolean DEFAULT false,
    extra_destination_address text,
    passenger_pays text,
    bilingual text,
    email text,
    extra_specs text,
    status text DEFAULT 'pending',
    vehicle_image text,
    fechadesolicitud text,
    distance_km numeric
);

-- 6. Table: viajes_confirmados
CREATE TABLE IF NOT EXISTS public.viajes_confirmados (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    created_at timestamp with time zone DEFAULT now(),
    cotizacion_id uuid REFERENCES public.cotizaciones(id) ON DELETE SET NULL,
    conductor_id uuid REFERENCES public.conductores(id) ON DELETE SET NULL,
    status text DEFAULT 'asignado',
    vehicle_model text,
    vehicle_image text,
    schedule text,
    booker_name text,
    passenger_phone text,
    booker_phone text,
    zone_rate text,
    monto_cobrar numeric,
    payment_method text,
    pickup_address text,
    pickup_zip text,
    pickup_ext_num text,
    pickup_municipality text,
    dropoff_address text,
    dropoff_zip text,
    dropoff_municipality text,
    adults integer,
    kids integer,
    pasajeros_adultos integer,
    pasajeros_ninos integer,
    luggage_10kg integer,
    luggage_25kg integer,
    carry_on integer,
    extra_destination boolean,
    extra_destination_address text,
    passenger_pays text,
    bilingual text,
    email text,
    extra_specs text,
    anotaciones text,
    distance_km numeric,
    distancia numeric,
    tiempoconductor integer DEFAULT 60
);

-- 7. Table: Notificaciones (capitalized)
CREATE TABLE IF NOT EXISTS public."Notificaciones" (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    mensaje text,
    tipo text,
    status text DEFAULT 'novista',
    referencia_id uuid,
    created_at timestamp with time zone DEFAULT now()
);

-- 8. Table: eventos
CREATE TABLE IF NOT EXISTS public.eventos (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    nombre text,
    created_at timestamp with time zone DEFAULT now()
);

-- 9. Table: facturacion
CREATE TABLE IF NOT EXISTS public.facturacion (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    created_at timestamp with time zone DEFAULT now(),
    razon_social text,
    rfc text,
    calle text,
    colonia text,
    municipio text,
    estado text,
    codigo_postal text,
    telefono text,
    email text,
    regimen_fiscal text,
    cantidad text,
    metodo_pago text,
    uso_cfdi text,
    fecha_servicio text,
    datos_adicionales text,
    status text DEFAULT 'pending'
);

